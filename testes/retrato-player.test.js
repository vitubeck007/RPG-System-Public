const { test } = require('node:test');
const assert = require('node:assert/strict');
const { iniciarServidor, abrirFicha, esperarAte } = require('./ajuda/ambiente');

test('player: foto e retrato independentes, lápis por modo e persistência do recorte', async () => {
  const s = await iniciarServidor();
  let f;
  try {
    const login = await s.api('/api/login', { nome: 'retrato', senha: 'teste', criarSeNaoExistir: true });
    const pasta = (await s.api('/api/personagens', { nome: 'Teste' }, login.token)).personagem.nomePasta;
    const abrir = () => abrirFicha(s, { player: 'retrato', nomePasta: pasta, token: login.token });
    f = await abrir();
    assert.equal(f.run('typeof criarRecorteRetrato'), 'function');
    f.window.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
    let arquivos = 0;
    f.document.querySelector('.sheet-portrait-editor input[type=file]').addEventListener('click', () => arquivos++);
    f.document.getElementById('avatar-ver-foto').click();
    assert.ok(f.document.querySelector('dialog.retrato-foto-completa'));
    assert.equal(arquivos, 0, 'visualizar a imagem não solicita arquivo');
    f.document.querySelector('dialog.retrato-foto-completa').remove();
    f.document.querySelector('.sheet-retrato-enviar').click();
    assert.equal(arquivos, 0, 'câmera não abre explorador');
    assert.equal(f.document.getElementById('avatar-arquivo-modal').hidden, false);
    f.run("RPGUI.fecharModal('avatar-arquivo-modal')");
    const { crc32 } = require('../servidor/imagens');
    const { deflateSync } = require('node:zlib');
    const chunk = (tipo, dados) => {
      const b = Buffer.alloc(dados.length + 12);
      b.writeUInt32BE(dados.length); b.write(tipo, 4); dados.copy(b, 8);
      b.writeUInt32BE(crc32(b.subarray(4, -4)), b.length - 4); return b;
    };
    const cabecalho = Buffer.alloc(13);
    cabecalho.writeUInt32BE(1024); cabecalho.writeUInt32BE(1024, 4); cabecalho[8] = 8; cabecalho[9] = 6;
    const png = Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), chunk('IHDR', cabecalho), chunk('IDAT', deflateSync(Buffer.alloc(1024 * (1 + 1024 * 4)))), chunk('IEND', Buffer.alloc(0))]);
    const enviar = (rota, token = login.token) => fetch(s.url + rota, { method:'POST', headers:{'Content-Type':'image/png', Authorization:`Bearer ${token}`}, body:png });
    assert.equal((await enviar('/api/imagens-fotos', 'invalido')).status, 401);
    const fotoEnviada = await enviar('/api/imagens-fotos');
    assert.equal(fotoEnviada.status, 200);
    const urlFoto = (await fotoEnviada.json()).imagem;
    const bytes = Buffer.from(await (await fetch(s.url + urlFoto)).arrayBuffer());
    assert.equal(bytes.readUInt32BE(16), 1024);
    assert.equal((await enviar('/api/imagens')).status, 400);
    const fs = require('node:fs'), path = require('node:path');
    fs.mkdirSync(path.join(s.dir, 'imagens', 'players'), { recursive:true });
    fs.writeFileSync(path.join(s.dir, 'imagens', 'players', 'foto teste.png'), png);
    f.run('abrirFotoPlayerPorNome()');
    f.document.getElementById('avatar-arquivo-nome').value = 'foto teste.png';
    f.document.getElementById('avatar-arquivo-form').dispatchEvent(new f.window.Event('submit', { bubbles:true, cancelable:true }));
    await esperarAte(() => f.run('FICHA.perfil.avatar') === '/imagens/players/foto%20teste.png');
    await f.salvos();
    assert.equal(f.document.getElementById('avatar-arquivo-modal').hidden, true);
    assert.equal(f.document.querySelector('.sheet-retrato-menu-acoes').contains(f.document.querySelector('.sheet-retrato-enviar')), true);

    const foto = f.document.getElementById('avatar-url-input');
    const retrato = f.document.getElementById('avatar-retrato-input');
    foto.value = 'https://example.com/foto.png';
    foto.dispatchEvent(new f.window.Event('input'));
    f.run("definirModoImagemPlayer('retrato')");
    assert.equal(f.document.getElementById('avatar-foto-campo').hidden, true);
    assert.equal(f.document.querySelector('[data-retrato-alvo="avatar-url-input"]').hidden, true);
    assert.equal(f.document.querySelector('[data-retrato-alvo="avatar-retrato-input"]').hidden, false);
    assert.equal(f.document.querySelector('[data-retrato-alvo="avatar-retrato-input"]').disabled, false);
    retrato.value = 'https://example.com/retrato.png';
    retrato.dispatchEvent(new f.window.Event('change'));
    await f.salvos();
    assert.equal(s.lerArquivo('retrato', pasta, 'perfil').avatarRetrato, retrato.value);
    assert.equal(s.lerArquivo('retrato', pasta, 'perfil').avatarOriginal, '/imagens/players/foto%20teste.png', 'enquadrar não substitui a origem');
    f.fechar(); f = await abrir();
    assert.equal(f.document.querySelector('[data-retrato-alvo="avatar-url-input"]').disabled, false, 'lápis pronto ao carregar, sem alternar os modos');
    assert.equal(f.document.getElementById('char-avatar-img').getAttribute('src'), 'https://example.com/retrato.png');
    assert.equal(f.document.getElementById('char-bio-portrait').getAttribute('src'), 'https://example.com/foto.png');
    assert.equal(f.document.getElementById('char-bio-portrait').dataset.fotoCompleta, '/imagens/players/foto%20teste.png');
    f.window.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
    f.document.getElementById('avatar-ver-foto').click();
    const ampliada = f.document.querySelector('.retrato-foto-completa img');
    assert.equal(ampliada.getAttribute('src'), '/imagens/players/foto%20teste.png');
    const original = Buffer.from(await (await fetch(s.url + ampliada.getAttribute('src'))).arrayBuffer());
    assert.deepEqual(original, png, 'ampliação recebe os bytes originais, sem redimensionamento');
    f.document.querySelector('.retrato-foto-completa').remove();
    assert.equal(f.document.getElementById('avatar-url-input').type, 'hidden');
    assert.ok([...f.document.querySelectorAll('.sheet-portrait-editor .retrato-acoes')].every(el => el.hidden));
    assert.equal(f.run('typeof openAvatarModal'), 'undefined');
    assert.equal(f.document.getElementById('avatar-modal'), null);
    f.run("definirModoImagemPlayer('foto')");
    assert.equal(f.document.getElementById('avatar-foto-campo').hidden, false);
    assert.deepEqual(f.erros, []);
  } finally { f?.fechar(); await s.parar(); }
});
